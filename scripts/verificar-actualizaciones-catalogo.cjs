const assert = require('node:assert/strict');
const { EventEmitter } = require('node:events');
const fs = require('node:fs'), vm = require('node:vm');
const { createUpdates, INTERVAL } = require('../catalogo-desktop/actualizaciones.cjs');
const callbacks = [], handlers = new Map(), messages = [];
const clock = {setTimeout(fn,ms){callbacks.push({fn,ms,type:'timeout'});return {};},setInterval(fn,ms){callbacks.push({fn,ms,type:'interval'});return {};},clearTimeout(){},clearInterval(){}};
const updater = new EventEmitter();
let loads = 0, checks = 0, downloads = 0, installs = 0, answer = 0, complete;
updater.checkForUpdates = async () => {checks++;};
updater.downloadUpdate = () => {downloads++; return new Promise(resolve=>{complete=resolve;});};
updater.quitAndInstall = (...args) => {assert.deepEqual(args,[false,true]);installs++;};
const contents = {mainFrame:{url:'catalogo://app/catalogo/catalogo.html'},send(...args){messages.push(args);}};
const trusted = {sender:contents,senderFrame:contents.mainFrame};
const controller=createUpdates({app:{isPackaged:true},ipcMain:{handle(k,v){handlers.set(k,v);},removeHandler(k){handlers.delete(k);}},getWindow:()=>({isDestroyed:()=>false,webContents:contents}),dialog:{showMessageBox:async()=>({response:answer})},loadUpdater:()=>{loads++;return updater;},timers:clock});
(async()=>{
  assert.equal(loads,0,'La búsqueda de actualizaciones no bloquea el arranque.');
  assert.equal(INTERVAL,600000);assert(callbacks.some(t=>t.type==='interval'&&t.ms===600000));
  await Promise.all([controller.check(),controller.check()]);assert.equal(checks,1);
  assert.equal(updater.autoDownload,false);assert.equal(updater.autoInstallOnAppQuit,false);assert.equal(updater.allowDowngrade,false);
  updater.emit('update-available',{version:'0.1.13-beta.1'});
  assert.equal(controller.getState().stage,'available');
  assert.equal(handlers.get('catalogo-updates:get')({}),null);
  await assert.rejects(handlers.get('catalogo-updates:download')({}),/Origen/);
  const a=handlers.get('catalogo-updates:download')(trusted),b=handlers.get('catalogo-updates:download')(trusted);
  await Promise.resolve();assert.equal(downloads,1);
  updater.emit('download-progress',{percent:41.5});assert.equal(controller.getState().percent,42);
  updater.emit('update-downloaded',{version:'0.1.13-beta.1'});complete();await Promise.all([a,b]);
  assert.equal(controller.getState().stage,'ready');
  await handlers.get('catalogo-updates:install')(trusted);assert.equal(installs,0);
  answer=1;await handlers.get('catalogo-updates:install')(trusted);assert.equal(installs,1);
  controller.dispose();assert.equal(handlers.size,0);

  const events={},ipc={},ticks=[];
  function element(){return {hidden:false,children:[],textContent:'',setAttribute(){},append(...nodes){this.children.push(...nodes);}};}
  const document={head:element(),body:element(),hidden:false,createElement:element};
  const context={document,window:{addEventListener(k,fn){events[k]=fn;}},require(name){assert.equal(name,'electron');return {ipcRenderer:{on(k,fn){ipc[k]=fn;},invoke:async()=>({stage:'available',version:'0.1.13-beta.1'})}};},setTimeout(fn,ms){ticks.push({fn,ms,type:'timeout'});return ticks.length;},clearTimeout(){},setInterval(fn,ms){ticks.push({fn,ms,type:'interval'});return ticks.length;},clearInterval(){}};
  vm.runInNewContext(fs.readFileSync('catalogo-desktop/preload.cjs','utf8'),context);
  events.DOMContentLoaded();await Promise.resolve();
  const panel=document.body.children[0];assert.equal(panel.hidden,false);
  const hide=ticks.find(t=>t.type==='timeout'&&t.ms===12000);assert(hide);hide.fn();assert.equal(panel.hidden,true);
  const reminder=ticks.find(t=>t.type==='interval');assert.equal(reminder.ms,600000);
  reminder.fn();assert.equal(panel.hidden,false,'El aviso vuelve a los diez minutos.');
  panel.children[3].onclick();assert.equal(panel.hidden,true);
  document.hidden=true;reminder.fn();assert.equal(panel.hidden,true,'No abrir avisos si la ventana está oculta.');
  document.hidden=false;ipc['catalogo-updates:state']({}, {stage:'downloading',version:'0.1.13-beta.1',percent:20});
  panel.children[3].onclick();reminder.fn();assert.equal(panel.hidden,true,'No repetir avisos durante la descarga.');
  ipc['catalogo-updates:state']({}, {stage:'ready',version:'0.1.13-beta.1'});assert.equal(panel.hidden,false);
  console.log('OK: aviso cada 10 minutos, ocultación automática, descarga por clic sin duplicados, instalación confirmada, sin instalación al cerrar, IPC restringido y carga diferida.');
})().catch(error=>{console.error(error);process.exitCode=1;});
