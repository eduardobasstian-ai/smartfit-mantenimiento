const fs = require('node:fs'), vm = require('node:vm'), assert = require('node:assert/strict');
let resolveFetch, calls = 0;
const pendingFetch = () => { calls++; return new Promise(resolve => { resolveFetch = resolve; }); };
const sandbox = {window:{dispatchEvent(){}},Event,CustomEvent,performance,fetch:pendingFetch,crypto};
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync('catalogo/equipos/sincronizacion.js','utf8'),sandbox);
const sync=sandbox.window.CatalogSync;
const settings=role=>({role,url:'https://test.invalid',key:'test',getToken:async()=> 'test'});
const context=role=>({role,allSites:role!=='supervisor',sites:[],technicians:[],canEdit:false,canExport:false});
const flush=()=>new Promise(resolve=>setImmediate(resolve));
(async()=>{
  sync.connect(settings('supervisor'));
  const first=sync.readOrdersContext(), second=sync.readOrdersContext();
  await flush(); assert.equal(calls,1);
  resolveFetch({ok:true,json:async()=>context('supervisor')});
  await Promise.all([first,second]);
  await sync.readOrdersContext(); assert.equal(calls,1,'No repetir peticiones dentro de la caché');
  sync.connect(settings('administrador'));
  const stale=sync.readOrdersContext();await flush();
  sync.disconnect();resolveFetch({ok:true,json:async()=>context('administrador')});
  await assert.rejects(stale,/sesión cambió/);
  await assert.rejects(sync.readOrdersContext(),/Inicia sesión/);
  sync.connect(settings('bodega'));
  assert.equal(sync.canWrite,false);
  const validBodega=sync.readOrdersContext();await flush();
  resolveFetch({ok:true,json:async()=>context('bodega')});
  const bodegaScope=await validBodega;
  assert.equal(bodegaScope.allSites,true,'Bodega consulta todas las sedes');
  assert.equal(bodegaScope.canEdit,false,'Bodega no puede editar');
  assert.equal(bodegaScope.canExport,false,'Bodega no puede exportar');
  sync.connect(settings('bodega'));
  const invalid=sync.readOrdersContext();await flush();
  resolveFetch({ok:true,json:async()=>({...context('supervisor'),allSites:true})});
  await assert.rejects(invalid,/inválido/);
  console.log('OK: peticiones deduplicadas, caché por sesión, respuesta antigua descartada, sesión cerrada y Bodega sin escritura.');
})().catch(error=>{console.error(error);process.exitCode=1;});
